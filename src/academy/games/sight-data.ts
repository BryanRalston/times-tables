export const SIGHT_LEVELS = ["preprimer", "primer", "first", "second", "third"] as const;
export type SightList = (typeof SIGHT_LEVELS)[number];

export interface SightWord {
  id: string;
  word: string;
  list: SightList;
  emoji: string;
  sentence: string;
}

function pack(list: SightList, rows: ReadonlyArray<readonly [string, string, string]>): SightWord[] {
  return rows.map(([word, emoji, sentence]) => ({
    id: `sw:${word.toLowerCase()}`,
    word,
    list,
    emoji,
    sentence,
  }));
}

