const BY_LIST: Record<SightList, readonly SightWord[]> = {
  preprimer: PREPRIMER,
  primer: PRIMER,
  first: FIRST,
  second: SECOND,
  third: THIRD,
};

export const ALL_SIGHT: readonly SightWord[] = [...PREPRIMER, ...PRIMER, ...FIRST, ...SECOND, ...THIRD];

export function sightWords(list: SightList): readonly SightWord[] {
  return BY_LIST[list];
}

export function isSightList(value: unknown): value is SightList {
  return typeof value === "string" && (SIGHT_LEVELS as readonly string[]).includes(value);
}
