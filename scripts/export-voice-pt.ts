import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { installPortuguese, setLocale } from "../src/academy/i18n";
import * as portuguese from "../src/academy/i18n-pt";
import { collectClipSpecs, collectSpokenLines, isSpanishPrecacheKey, lineChunkErrors } from "../src/academy/voice/catalog";
import { spokenText } from "../src/academy/voice/pronounce";

installPortuguese(portuguese);
setLocale("pt");

const lines = collectSpokenLines();
const errors = lineChunkErrors(lines);
if (errors.length > 0) {
  for (const error of errors.slice(0, 12)) {
    console.error(`${error.game}: ${error.error}\n  ${error.line}`);
  }
  console.error(`${errors.length} Portuguese lines cannot be clipped`);
  process.exit(1);
}

const specs = collectClipSpecs(lines);
const files: Record<string, string> = {};
const jobs: { key: string; say: string; file: string }[] = [];
for (const spec of specs) {
  const say = spokenText(spec.key);
  const slug = spec.key
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/ç/g, "c")
    .replace(/ñ/g, "n")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 42);
  const hash = createHash("sha1").update(`pt\0${spec.key}\0${say}`).digest("hex").slice(0, 8);
  const file = `pt/${slug || "clip"}-${hash}.mp3`;
  files[spec.key] = file;
  jobs.push({ key: spec.key, say, file });
}

const body = `/** Generated by scripts/export-voice-pt.ts. Do not edit by hand. */
export const VOICE_MODEL_PT = {
  engine: "Kokoro",
  voice: "pf_dora",
  model: "hexgrad/Kokoro-82M",
  license: "Apache-2.0",
} as const;

export const VOICE_FILES_PT: Record<string, string> = ${JSON.stringify(files, null, 2)};
`;

writeFileSync(resolve("src/academy/voice/manifest-pt.ts"), body);
writeFileSync("/tmp/voice-jobs-pt.json", `${JSON.stringify(jobs)}\n`);
const precache = specs
  .filter((spec) => isSpanishPrecacheKey(spec.key, new Set(spec.games)))
  .map((spec) => files[spec.key])
  .filter((file): file is string => Boolean(file))
  .sort();
writeFileSync(resolve("src/academy/voice/pt-precache.json"), `${JSON.stringify(precache, null, 2)}\n`);
console.log(`${lines.length} Portuguese lines, ${jobs.length} clips, ${precache.length} precached, all under voice/pt/`);
