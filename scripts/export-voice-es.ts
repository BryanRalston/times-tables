import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { setLocale } from "../src/academy/i18n";
import { collectClipSpecs, collectSpokenLines, lineChunkErrors } from "../src/academy/voice/catalog";
import { spokenText } from "../src/academy/voice/pronounce";

setLocale("es");

const lines = collectSpokenLines();
const errors = lineChunkErrors(lines);
if (errors.length > 0) {
  for (const error of errors.slice(0, 12)) {
    console.error(`${error.game}: ${error.error}\n  ${error.line}`);
  }
  console.error(`${errors.length} Spanish lines cannot be clipped`);
  process.exit(1);
}

const specs = collectClipSpecs(lines);
const files: Record<string, string> = {};
const jobs: { key: string; say: string; file: string }[] = [];
for (const spec of specs) {
  const say = spokenText(spec.key);
  const slug = spec.key
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/ñ/g, "n")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 42);
  const hash = createHash("sha1").update(`es\0${spec.key}\0${say}`).digest("hex").slice(0, 8);
  const file = `es/${slug || "clip"}-${hash}.mp3`;
  files[spec.key] = file;
  jobs.push({ key: spec.key, say, file });
}

const body = `/** Generated by scripts/export-voice-es.ts. Do not edit by hand. */
export const VOICE_MODEL_ES = {
  engine: "Kokoro",
  voice: "ef_dora",
  model: "hexgrad/Kokoro-82M",
  license: "Apache-2.0",
} as const;

export const VOICE_FILES_ES: Record<string, string> = ${JSON.stringify(files, null, 2)};
`;

writeFileSync(resolve("src/academy/voice/manifest-es.ts"), body);
writeFileSync("/tmp/voice-jobs-es.json", `${JSON.stringify(jobs)}\n`);
console.log(`${lines.length} Spanish lines, ${jobs.length} clips, all under voice/es/`);
