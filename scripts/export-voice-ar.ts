import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { installArabic, setLocale } from "../src/academy/i18n";
import * as arabic from "../src/academy/i18n-ar";
import { collectClipSpecs, collectSpokenLines, isSpanishPrecacheKey, lineChunkErrors } from "../src/academy/voice/catalog";
import { spokenText } from "../src/academy/voice/pronounce";

installArabic(arabic);
setLocale("ar");

const lines = collectSpokenLines();
const errors = lineChunkErrors(lines);
if (errors.length > 0) {
  for (const error of errors.slice(0, 30)) {
    console.error(`${error.game}: ${error.error}\n  ${error.line}`);
  }
  console.error(`${errors.length} Arabic lines cannot be clipped`);
  process.exit(1);
}

const specs = collectClipSpecs(lines);
const files: Record<string, string> = {};
const jobs: { key: string; say: string; file: string }[] = [];
for (const spec of specs) {
  const say = spokenText(spec.key);
  const slug = spec.key
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 42);
  const hash = createHash("sha1").update(`ar\0${spec.key}\0${say}`).digest("hex").slice(0, 8);
  const file = `ar/${slug || "clip"}-${hash}.mp3`;
  files[spec.key] = file;
  jobs.push({ key: spec.key, say, file });
}

const body = `/** Generated by scripts/export-voice-ar.ts. Do not edit by hand. */
export const VOICE_MODEL_AR = {
  engine: "eSpeak NG",
  voice: "ar",
  model: "espeak-ng",
  license: "GPL-3.0",
} as const;

export const VOICE_FILES_AR: Record<string, string> = ${JSON.stringify(files, null, 2)};
`;

writeFileSync(resolve("src/academy/voice/manifest-ar.ts"), body);
writeFileSync("/tmp/voice-jobs-ar.json", `${JSON.stringify(jobs)}\n`);
const precache = specs
  .filter((spec) => isSpanishPrecacheKey(spec.key, new Set(spec.games)))
  .map((spec) => files[spec.key])
  .filter((file): file is string => Boolean(file))
  .sort();
writeFileSync(resolve("src/academy/voice/ar-precache.json"), `${JSON.stringify(precache, null, 2)}\n`);
console.log(`${lines.length} Arabic lines, ${jobs.length} clips, ${precache.length} precached, all under voice/ar/`);
